-- Показатели канала звонков в каталоге.
--
-- Воронка звонков описана в коде с самого её появления: выгрузки обращений и
-- звонков имеют одинаковые заголовки, канал объявляет загружающий, и складывать
-- их в один показатель нельзя. Но в каталог базы эти четыре показателя не
-- попали, из-за чего допуск на публикацию нельзя было расширить до полного
-- состава: проверка справедливо отвергала показатели вне каталога.
--
-- Миграция аддитивная: существующие показатели не меняются.
SET LOCAL search_path = pilot_r1, public, pg_catalog;

INSERT INTO metric_catalog(code,display_name,unit,is_count,is_additive) VALUES
 ('callTraffic','Звонки: трафик','COUNT',true,true),
 ('callVisits','Звонки: визиты','COUNT',true,true),
 ('callDeals','Звонки: сделки','COUNT',true,true),
 ('callTrafficToDeal','Конверсия звонок → сделка','PCT',false,false)
ON CONFLICT (code) DO NOTHING;
