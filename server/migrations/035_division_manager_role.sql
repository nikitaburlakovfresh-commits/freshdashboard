-- Роль «Дивизиональный руководитель».
--
-- Требование владельца (20.09.2026): дивизиональный уровень управления должен
-- быть выражен ролью, а не только структурой справочника. В справочнике
-- дивизионы уже есть: Дивизион Бурлакова (4 зоны РМ, 26 филиалов) и Дивизион
-- Мелояна (4 зоны РМ, 17 филиалов).
--
-- Область роли — ORG_UNIT, как у REGIONAL_MANAGER. Причина: разрешение области
-- действия грантов в currentOperationalRolesByOrg и currentRmOrgIds
-- (workItemService.ts:54-62) сопоставляет org_unit_id напрямую и не
-- разворачивает грант в поддерево. Грант на узел DIVISION база приняла бы
-- (role_grants.org_unit_id ссылается на org_directory_units, куда входят и
-- дивизионы), но он остался бы пустым: к узлу дивизиона не привязаны ни
-- задачи, ни факты. Поэтому роль выдаётся по филиалам дивизиона, как сейчас
-- выдаётся REGIONAL_MANAGER.
--
-- Разворот гранта дивизиона и зоны РМ в филиалы по истории привязок на дату
-- расчёта вынесен отдельным шагом: он затрагивает ядро авторизации и требует
-- тестов. После него одного гранта на дивизион будет достаточно.
--
-- Набор прав копируется из REGIONAL_MANAGER: дивизиональный руководитель
-- ставит и принимает задачи и читает показатели своих филиалов, но не является
-- исполнителем. Набор задан выборкой, а не перечислением, чтобы роли не
-- разошлись при будущих изменениях прав РМ.
--
-- Людей эта миграция не назначает: выдача роли конкретному пользователю
-- выполняется живым администратором в панели портала (решение миграции 029).
--
-- Аддитивная, повторный прогон безопасен. Неразрушающий откат:
-- DELETE FROM role_permissions WHERE role_code='DIVISION_MANAGER';
-- DELETE FROM roles WHERE code='DIVISION_MANAGER';  -- при отсутствии грантов

INSERT INTO roles(code,display_name,scope_kind,is_system)
VALUES ('DIVISION_MANAGER','Дивизиональный руководитель','ORG_UNIT',false)
ON CONFLICT DO NOTHING;

INSERT INTO role_permissions(role_code,permission_code)
SELECT 'DIVISION_MANAGER', rp.permission_code
FROM role_permissions rp
WHERE rp.role_code = 'REGIONAL_MANAGER'
ON CONFLICT DO NOTHING;
