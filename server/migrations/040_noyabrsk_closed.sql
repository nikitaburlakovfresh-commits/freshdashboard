-- Ноябрьск: филиал не будет запущен.
--
-- Решение владельца (21.09.2026): «Ноябрьск просто не будет запускаться,
-- несмотря на то что есть в таблицах, поставь его как закрыто и не отображай.
-- Если далее будет открытие в этом городе, то я в панели админ его запущу».
--
-- Почему состояние CLOSED, а не удаление записи: на 21.09.2026 у филиала
-- 44 опубликованных значения показателей и он присутствует в семи отчётах
-- QLIK за 20.09. Удаление записи оставило бы эти значения без филиала и
-- исказило бы сентябрьскую отчётность задним числом. Правило проекта прямо
-- запрещает разрушающие операции.
--
-- Состояние CLOSED убирает филиал из рабочих экранов, но сохраняет историю.
-- Запуск в будущем выполняется в портале через оргструктуру и активацию с
-- датой вступления в силу — правка кода не требуется.
--
-- Аддитивная по смыслу, повторный прогон безопасен. Неразрушающий откат:
-- UPDATE org_directory_units SET lifecycle_state = 'PRE_LAUNCH' WHERE code = 'BR-NOYABRSK';

-- Справочник защищён триггером org_directory_identity_immutable: он запрещает
-- любое изменение записи филиала и в тексте ошибки требует «отдельно
-- рассмотренную миграцию». Это она. Защита снимается ровно на одну операцию
-- по одному филиалу и возвращается в этой же транзакции — если что-то пойдёт
-- не так, откат вернёт и защиту.
ALTER TABLE org_directory_units DISABLE TRIGGER org_directory_identity_immutable;

DO $$
DECLARE changed integer;
BEGIN
  UPDATE org_directory_units
     SET lifecycle_state = 'CLOSED'
   WHERE code = 'BR-NOYABRSK'
     AND lifecycle_state <> 'CLOSED';
  GET DIAGNOSTICS changed = ROW_COUNT;
  -- Затронуться может только один филиал. Больше — значит условие ошибочно,
  -- и менять справочник нельзя.
  IF changed > 1 THEN
    RAISE EXCEPTION 'Ожидался один филиал, изменено %', changed;
  END IF;
END $$;

ALTER TABLE org_directory_units ENABLE TRIGGER org_directory_identity_immutable;
