-- Полнота прав роли SUPER_ADMIN: исполнительские действия по задачам.
--
-- Решение владельца (20.09.2026): Никита Бурлаков — дивизиональный руководитель
-- и одновременно ответственный за разработку портала, поэтому роль создателя
-- администратора должна покрывать весь функционал портала без исключений.
--
-- Миграция 033 привязала административные права; оставались три исполнительских
-- права, закреплённых за операционными ролями РФ, РОО и РОП.
--
-- Расширения полномочий по существу не происходит. Доменные проверки задач
-- опираются не на это право, а на операционную роль в конкретном филиале и на
-- совпадение исполнителя: submitWorkItem требует
-- submitRolesHeld.has(submitOwnerRole) AND assignee_user_id = актор.
-- Право открывает маршрут, но сдать чужую задачу или задачу в филиале без
-- операционной роли по-прежнему нельзя. Чтобы действительно работать
-- исполнителем, нужен отдельный грант операционной роли по филиалу — он
-- выдаётся в панели администратора и здесь не назначается.
--
-- Аддитивная, ничего не отзывает, повторный прогон безопасен.
-- Неразрушающий откат — DELETE перечисленных пар из role_permissions.

INSERT INTO role_permissions(role_code,permission_code) VALUES
 ('SUPER_ADMIN','work_item.start'),
 ('SUPER_ADMIN','work_item.submit'),
 ('SUPER_ADMIN','work_item.fields.write')
ON CONFLICT DO NOTHING;
