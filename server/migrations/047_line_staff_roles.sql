-- Линейные должности филиала: исполнители задач внутри отделов.
--
-- Решение владельца 21.09.2026. В каталоге ролей были руководители отделов
-- (РОП, РОО, руководитель КСО), но не было тех, кем эти руководители управляют.
-- Из-за этого задачу нельзя было передать конкретному менеджеру: портал
-- допускает исполнителем только того, у кого есть право роли, названной
-- владельцем шаблона задачи. Именно это ограничение и блокировало
-- делегирование, а не отсутствие отдельного механизма передачи.
--
-- Добавляются пять должностей уровня филиала:
--   SMOP      Старший менеджер отдела продаж (СМОП)
--   SMOO      Старший менеджер отдела оценки (СЭО)
--   MOP       Менеджер отдела продаж (МОП)
--   EO        Эксперт отдела оценки (ЭО)
--   KSO_STAFF Сотрудник КСО
--
-- Права даются ровно те же шесть, что миграция 009 дала РОП и РОО: читать свою
-- задачу, начать её, заполнять поля, сдавать итог, видеть историю и получать
-- уведомления. Ни одного права на показатели, публикацию, приёмку или
-- администрирование. Линейный сотрудник видит то, что ему поручено, и ничего
-- сверх этого.
--
-- Ежедневника у этих должностей нет: движок ежедневников поддерживает РФ, РОП и
-- РОО, и расширять его здесь не требуется — решение владельца «только
-- делегирование без их ежедневника».
--
-- is_system = false: это роли сети, а не платформы, владелец вправе их менять и
-- переименовывать через панель администратора.
--
-- Аддитивная. Повторный прогон безопасен.
-- Неразрушающий откат:
--   DELETE FROM role_permissions WHERE role_code IN ('SMOP','SMOO','MOP','EO','KSO_STAFF');
--   DELETE FROM roles WHERE code IN ('SMOP','SMOO','MOP','EO','KSO_STAFF');
--   -- выполнимо только пока по этим ролям нет ни одного гранта.

INSERT INTO roles(code, display_name, scope_kind, is_system) VALUES
  ('SMOP',      'Старший менеджер отдела продаж (СМОП)', 'ORG_UNIT', false),
  ('SMOO',      'Старший менеджер отдела оценки (СЭО)',  'ORG_UNIT', false),
  ('MOP',       'Менеджер отдела продаж (МОП)',          'ORG_UNIT', false),
  ('EO',        'Эксперт отдела оценки (ЭО)',            'ORG_UNIT', false),
  ('KSO_STAFF', 'Сотрудник КСО',                         'ORG_UNIT', false)
ON CONFLICT DO NOTHING;

-- Без этих строк грант роли невидим для проверок доступа: getEffectiveGrants
-- соединяет права с грантами по коду роли, и роль без прав не даёт ни одной
-- строки эффективных прав (см. пояснение в миграции 009).
INSERT INTO role_permissions(role_code, permission_code)
SELECT r.role_code, p.code
FROM (VALUES ('SMOP'), ('SMOO'), ('MOP'), ('EO'), ('KSO_STAFF')) AS r(role_code)
CROSS JOIN permissions p
WHERE p.code IN (
  'work_item.read', 'work_item.start', 'work_item.fields.write',
  'work_item.submit', 'work_item.history.read', 'notification.read'
)
ON CONFLICT (role_code, permission_code) DO NOTHING;
