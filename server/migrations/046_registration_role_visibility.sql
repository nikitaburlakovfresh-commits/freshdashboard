-- Какие должности предлагать в форме самостоятельной регистрации.
--
-- Было: форма предлагала все роли каталога, кроме владельца платформы и общего
-- логина филиала, — двадцать четыре позиции, включая служебные («Замещающий
-- BH», «Команда запуска», «Технический координатор»). Человек при регистрации
-- видел список, в котором его должности может не быть, зато есть роли, которые
-- ему выбирать незачем.
--
-- Становится: признак на роли. Список в форме правится в панели администратора
-- без изменения кода — требование настраиваемости. Скрытая роль остаётся
-- полноценной: её по-прежнему можно присвоить при подтверждении заявки и в
-- управлении правами, она лишь не предлагается человеку самому.
--
-- Значения по умолчанию здесь не расставляются: состав списка определяет
-- владелец, и пока он не решил, список остаётся прежним.
--
-- Аддитивная. Повторный прогон безопасен.
-- Неразрушающий откат:
--   UPDATE roles SET hidden_in_registration = false;
--   -- столбец не удаляется.

ALTER TABLE roles ADD COLUMN IF NOT EXISTS hidden_in_registration boolean NOT NULL DEFAULT false;
