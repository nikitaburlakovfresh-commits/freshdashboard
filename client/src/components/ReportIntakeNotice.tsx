import React from 'react';
import { useAuth } from '../auth/AuthContext';

/** BETA-01. Ограниченный первый выпуск может работать без антивирусного
 * контура. Запрет обеспечивает сервер; здесь только честное отображение
 * состояния, чтобы руководитель не считал скрытую кнопку защитой. Признак
 * отсутствует в старых ответах — тогда контур считается доступным. */
export function useReportIntakeEnabled(): boolean {
  const { me } = useAuth();
  return me?.features?.report_intake !== false;
}

export default function ReportIntakeNotice() {
  if (useReportIntakeEnabled()) return null;
  return (
    <section className="org-scope" role="status">
      <div>
        <strong>Загрузка отчётов и публикация показателей отключены</strong>
        <p>
          В этом выпуске контур антивирусной проверки не введён в работу, поэтому сервер отклоняет
          приём новых оригиналов, проверку, предпросмотр и публикацию. Это ограничение выпуска, а не
          ошибка доступа и не отсутствие права.
        </p>
        <p>
          Ранее опубликованные показатели остаются доступны для чтения. Задачи, ежедневники,
          пользователи и назначения работают без ограничений. Отсутствие новых данных не означает
          нулевые значения.
        </p>
      </div>
    </section>
  );
}
